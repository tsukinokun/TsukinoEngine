#pragma once
// 名前空間 : Tsukino::BuiltIn::ECS
namespace Tsukino::BuiltIn::ECS {
    //--------------------------------------------------------------
    //! @struct MotionBlurComponent
    //! @brief  オブジェクト速度バッファ方式モーションブラーの設定
    //! @note   カメラエンティティにアタッチして使う。
    //!         このコンポーネントが存在しなければモーションブラーは無効。
    //!         SkyAtmosphereComponent と同じく「付ける／付けない」で
    //!         機能そのもののON/OFFを表現する。
    //!
    //!         強度をゲーム側の演出に連動させたい場合（例：攻撃中だけ強くする）は、
    //!         アプリ層のSystemから strength を毎フレーム書き換えればよい。
    //--------------------------------------------------------------
    struct MotionBlurComponent {
        //----------------------------------------------------------
        // 有効・無効
        //----------------------------------------------------------
        bool enabled = true;    // false ならブラーパスをスキップする

        //----------------------------------------------------------
        // ブラーの効き
        //----------------------------------------------------------
        float strength      = 1.0f;     // 速度ベクトルの倍率。攻撃時などに上げる
        float maxBlurRadius = 0.03f;    // UV単位のブラー長クランプ（高速移動時に画面が溶けるのを防ぐ）
        int   sampleCount   = 8;        // サンプル数（1〜16。多いほど滑らかで重い）

        //----------------------------------------------------------
        // シャッター補正
        //----------------------------------------------------------
        //! @brief 基準フレームレート
        //! @note  速度バッファには「1フレームあたりの移動量」が入っているため、
        //!        フレームレートが変わるとブラーの長さも変わってしまう。
        //!        targetFps * deltaTime を掛けて、この基準fpsで動いていたときの
        //!        見た目に揃える。
        float targetFps = 60.0f;
    };
}    // namespace Tsukino::BuiltIn::ECS
