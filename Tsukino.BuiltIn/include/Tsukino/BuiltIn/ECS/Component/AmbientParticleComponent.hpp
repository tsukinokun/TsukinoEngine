#pragma once
#include <hlsl++.h>
// 名前空間 : Tsukino::BuiltIn::ECS
namespace Tsukino::BuiltIn::ECS {
    //--------------------------------------------------------------
    //! 空間に漂う環境パーティクルの設定
    //! @note 何に見せるかはゲーム側がパラメータで決める。色と大きさと速さを
    //!       変えれば、火の粉・灰・塵・雪・胞子・水中の浮遊物のいずれにもなる。
    //!       エンジンは「GPUで大量の板を漂わせる仕組み」だけを持ち、
    //!       絵の判断には踏み込まない。
    //!
    //!       FogComponent / SkyAtmosphereComponent と同じく
    //!       「アタッチする／しない」で機能そのもののON/OFFを表現する。
    //!       シーンに複数あっても最初の1つだけが使われる。
    //!
    //!       粒子はCPU側にもGPU側にも1粒あたりのメモリを持たない。位置も
    //!       大きさも速さも粒子番号のハッシュから毎フレーム計算し直すため、
    //!       count を増やしてもメモリは1バイトも増えない（増えるのは頂点
    //!       シェーダーの実行回数と塗りつぶし量だけ）。
    //!
    //!       粒子の座標はカメラを中心とした volumeSize のボリュームで
    //!       折り返される。このためカメラがどこまで移動しても、有限の count で
    //!       空間全体が埋まり続ける。ボリュームの外周では自動的にフェード
    //!       アウトするので、折り返しの瞬間が見えることはない。
    //!
    //!       既定値は「1ユニット = 1cm」のシーンを想定している。長さの次元を
    //!       持つ値（volumeSize / minSize / maxSize / driftVelocity /
    //!       swayAmplitude / nearFadeDistance）はワールドスケールに
    //!       合わせて入れ直すこと。
    //--------------------------------------------------------------
    struct AmbientParticleComponent {
        //----------------------------------------------------------
        // 有効・無効
        //----------------------------------------------------------
        bool enabled = true;    // false なら描画パスごとスキップする

        //----------------------------------------------------------
        // 粒子の量とボリューム
        //----------------------------------------------------------
        unsigned int   count      = 3000;                                        // 粒子数。上限は kMaxAmbientParticles でクランプされる
        hlslpp::float3 volumeSize = hlslpp::float3(2400.0f, 900.0f, 2400.0f);    // カメラを中心に折り返すボリュームの一辺
        unsigned int   seed       = 12345;                                       // 配置を決める乱数シード。下位24ビットだけが使われる

        //----------------------------------------------------------
        // 見た目
        //----------------------------------------------------------
        //! @note minSize / maxSize は板の半径（ワールド単位）。粒子ごとに
        //!       「大きい＝暗い＝遅い」⇔「小さい＝明るい＝速い」が相関するように
        //!       補間されるため、1回の描画で層のある絵になる。
        hlslpp::float3 color         = hlslpp::float3(1.0f, 1.0f, 1.0f);    // 粒子の色（linear）。暖色で火の粉、寒色で塵や雪になる
        float          intensity     = 1.0f;                                  // 全体の強度。HDRバッファへ加算するのでトーンマップで自然に丸まる
        float          minSize       = 0.8f;                                  // 一番小さい粒の半径（明るく速い側）
        float          maxSize       = 3.5f;                                  // 一番大きい粒の半径（暗く遅い側）
        float          minBrightness = 0.15f;                                 // 一番暗い粒の輝度倍率
        float          maxBrightness = 1.6f;                                  // 一番明るい粒の輝度倍率。1を超えるとHDRでにじむ
        float          twinkle       = 0.6f;                                  // きらめきの強さ。0で明滅なし、1で輝度が0まで落ちる

        //----------------------------------------------------------
        // 動き
        //----------------------------------------------------------
        //! @note driftVelocity を上向きにすると粒が舞い上がり、下向きにすると降る。
        //!       速度倍率が上記の層と相関するので、大きな粒はゆっくり漂い、
        //!       小さな粒は勢いよく流れていく。
        hlslpp::float3 driftVelocity = hlslpp::float3(10.0f, 20.0f, 3.0f);    // 全粒子に共通の流れ（ワールド単位/秒）
        float          swayAmplitude = 14.0f;                                 // サインの揺らぎの振幅（ワールド単位）
        float          swayFrequency = 0.8f;                                  // 揺らぎの角速度（rad/秒）。きらめきの周期もこれに連動する
        float          minSpeedScale = 0.35f;                                 // 一番遅い粒の速度倍率
        float          maxSpeedScale = 1.7f;                                  // 一番速い粒の速度倍率

        //----------------------------------------------------------
        // フェード
        //----------------------------------------------------------
        //! @note edgeFadeStart はボリューム半径に対する比率。1.0 で境界に
        //!       達してしまうので、必ず 1.0 未満にしないと折り返しが目に見える。
        float edgeFadeStart    = 0.65f;    // この比率から外周へ向けて消えていく
        float nearFadeDistance = 60.0f;    // カメラからこの距離までは消しておく（板が画面を覆うのを防ぐ）
    };
}    // namespace Tsukino::BuiltIn::ECS
