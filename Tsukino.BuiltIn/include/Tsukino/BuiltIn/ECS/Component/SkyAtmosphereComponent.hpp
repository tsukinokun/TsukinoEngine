#pragma once
#include <hlsl++.h>
// 名前空間 : Tsukino::BuiltIn::ECS
namespace Tsukino::BuiltIn::ECS {
    //--------------------------------------------------------------
    //! @struct SkyAtmosphereComponent
    //! @brief  大気散乱のパラメータを保持するコンポーネント
    //--------------------------------------------------------------
    struct SkyAtmosphereComponent {
        //----------------------------------------------------------
        // 散乱パラメータ
        //----------------------------------------------------------
        float rayleighScattering = 1.0f;     // レイリー散乱の強さ（青空の青み）
        float mieScattering      = 0.1f;     // ミー散乱の強さ（霞・もや）
        float mieAnisotropy      = 0.76f;    // ミー散乱の異方性（太陽周辺の光輪）

        //----------------------------------------------------------
        // 大気パラメータ
        //----------------------------------------------------------
        float atmosphereHeight = 8000.0f;       // 大気の厚さ（m）
        float planetRadius     = 6371000.0f;    // 地球の半径（m）

        //----------------------------------------------------------
        // 太陽パラメータ
        //----------------------------------------------------------
        float sunIntensity = 20.0f;    // 太陽の強度
        float sunDiskSize  = 0.02f;    // 太陽円盤の大きさ

        //----------------------------------------------------------
        // 地面カラー
        //----------------------------------------------------------
        hlslpp::float3 groundColor = hlslpp::float3(0.1f, 0.08f, 0.05f);
    };
}    // namespace Tsukino::BuiltIn::ECS
