#pragma once
#include <functional>
#include <entt/entt.hpp>
#include <Jolt/Jolt.h>
#include <Jolt/Physics/Body/BodyID.h>
#include <DirectXMath.h>
// 名前空間 : Tsukino::BuiltIn::ECS
namespace Tsukino::BuiltIn::ECS {
    //-------------------------------------------------------------------------
    // @enum  ColliderType
    // @brief 衝突判定に使用する形状の種類
    //-------------------------------------------------------------------------
    enum class ColliderType {
        Box,
        Sphere,
        Capsule
    };

    //-------------------------------------------------------------------------
    // @struct CollisionComponent
    // @brief  Jolt PhysicsのBody実体とECSエンティティを紐付けるためのデータ
    //-------------------------------------------------------------------------
    struct CollisionComponent {
        //---------------------------------------------------------------------
        // Joltから発行された一意の管理ID（JPH::BodyID）
        //---------------------------------------------------------------------
        JPH::BodyID bodyID;

        //---------------------------------------------------------------------
        // コリジョンの形状設定
        //---------------------------------------------------------------------
        ColliderType type = ColliderType::Box;

        //---------------------------------------------------------------------
        // 各形状のサイズデータ
        // Box    : 各軸の半分サイズ(Half Extents)
        // Sphere : x = 半径
        // Capsule: x = 半径, y = 半分の高さ
        //---------------------------------------------------------------------
        DirectX::XMFLOAT3 extent = {0.5f, 0.5f, 0.5f};

        //---------------------------------------------------------------------
        // センサー設定
        // true  : 当たり判定のみを行い、物理的な衝突（反発）は発生させない
        // false : 物理的な衝突計算を行い、物体を押し戻す
        //---------------------------------------------------------------------
        bool isSensor = true;

        //---------------------------------------------------------------------
        // Jolt側でBodyの実体が生成・登録されているかどうかのフラグ
        //---------------------------------------------------------------------
        bool isInitialized = false;

        //---------------------------------------------------------------------
        // 衝突開始イベントのコールバック関数
        //---------------------------------------------------------------------
        std::function<void(entt::entity)> onCollisionEnter = nullptr;

        //---------------------------------------------------------------------
        // @brief  保持しているBodyIDが有効なものかどうかを返す
        // @return 有効ならtrue
        //---------------------------------------------------------------------
        bool IsValid() const { return !bodyID.IsInvalid(); }
    };

}    // namespace Tsukino::BuiltIn::ECS
