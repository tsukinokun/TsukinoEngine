#pragma once
#include <hlsl++.h>
// 名前空間 : Tsukino::BuiltIn::ECS
namespace Tsukino::BuiltIn::ECS {
    //--------------------------------------------------------------
    //! @struct FogComponent
    //! @brief  距離フォグ・高さフォグ・ノイズ揺らぎの設定
    //! @note   SkyAtmosphereComponent / MotionBlurComponent と同じく
    //!         「アタッチする／しない」で機能そのもののON/OFFを表現する。
    //!         シーンに複数あっても最初の1つだけが使われる。
    //!
    //!         距離・高さのデフォルト値は「1ユニット = 1m」のシーンを想定している。
    //!         ワールドのスケールが違うプロジェクトでは density / startDistance /
    //!         height / heightFalloff / heightDensity / noiseScale / windSpeed を
    //!         そのスケールに合わせて設定すること（すべて長さの逆数か長さの次元を持つ）。
    //!
    //!         時間帯や状況で霧を濃くしたい場合（例：夜だけ濃霧にする）は、
    //!         アプリ層のSystemから density を毎フレーム書き換えればよい。
    //--------------------------------------------------------------
    struct FogComponent {
        //----------------------------------------------------------
        // 有効・無効
        //----------------------------------------------------------
        bool enabled = true;    // false ならフォグパスをスキップする

        //----------------------------------------------------------
        // 距離フォグ
        //----------------------------------------------------------
        hlslpp::float3 color         = hlslpp::float3(0.55f, 0.60f, 0.65f);    // フォグの色（linear）
        float          density       = 0.015f;                                 // 距離あたりの濃さ（1/m）
        float          startDistance = 10.0f;                                  // これより近くは霞ませない（m）
        float          maxOpacity    = 1.0f;                                   // 不透明度の上限。遠景を完全に消したくないときに下げる

        //----------------------------------------------------------
        // 高さフォグ（地面付近に霧が溜まる）
        //----------------------------------------------------------
        //! @note 背景（空）ピクセルには距離フォグを掛けないため、地平線を
        //!       霞ませているのはこの高さフォグ。無効にすると遠景の地形と
        //!       空の境目がはっきり出る。
        bool  heightFogEnabled = true;
        float height           = 2.0f;     // 霧が溜まる基準の高さ（m）
        float heightFalloff    = 0.25f;    // 上に行くほど薄くなる速さ。大きいほど霧が低く留まる
        float heightDensity    = 0.05f;    // 基準高さでの濃さ（1/m）

        //----------------------------------------------------------
        // 太陽方向の前方散乱
        //----------------------------------------------------------
        //! @note 太陽を覗き込む向きほどフォグ色がこの色へ寄る。
        //!       方向はDirectionalLightComponentの向きをそのまま使う。
        hlslpp::float3 sunColor        = hlslpp::float3(1.0f, 0.85f, 0.65f);
        float          sunScatterPower = 8.0f;    // 散乱の鋭さ（pow指数）。大きいほど太陽の周りだけ色づく

        //----------------------------------------------------------
        // ノイズによる揺らぎ
        //----------------------------------------------------------
        bool           noiseEnabled   = true;
        float          noiseScale     = 0.03f;                                // ワールド座標→ノイズ座標のスケール。小さいほど模様が大きい
        float          noiseIntensity = 0.4f;                                 // 0 = 濃さ一定, 1 = 最大の濃淡
        hlslpp::float3 windDirection  = hlslpp::float3(1.0f, 0.0f, 0.3f);    // 霧が流れる向き（Systemが正規化して転送する）
        float          windSpeed      = 0.5f;                                 // 霧が流れる速さ
    };
}    // namespace Tsukino::BuiltIn::ECS
