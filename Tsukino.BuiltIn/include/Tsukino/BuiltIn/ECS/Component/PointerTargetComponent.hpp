#pragma once
// 名前空間 : Tsukino::BuiltIn::ECS
namespace Tsukino::BuiltIn::ECS {
    //-------------------------------------------------------------
    //! @brief  マウスカーソルの重なりとクリックを受け取るためのコンポーネント
    //! @note   InteractionSystemが毎フレーム書く。画面空間（SpriteSpace::Screen）の
    //!         スプライトのうち、マウスの下で最も手前（sortOrderが大きい）の1つを選び、
    //!         そのエンティティか、親を辿って最初に見つかったこのコンポーネントを立てる。
    //!         手前に別のスプライト（暗転板など）が重なっていれば、奥のものは立たない。
    //!
    //!         当たり判定はスプライトの矩形そのもの。見た目と別の範囲で反応させたいときは、
    //!         色のアルファを0にした矩形スプライトへこのコンポーネントを付けて重ねる。
    //!         祖先に UIClipComponent があれば、その枠の外では当たらない。
    //!
    //!         clicked は通常「押した瞬間」に立つ。ただし祖先に ScrollViewComponent があるものは、
    //!         中身のドラッグと区別するため「押したものの上で離した瞬間」に立ち、
    //!         その押し込みでスクロールした場合は立たない
    //-------------------------------------------------------------
    struct PointerTargetComponent {
        bool hovered = false;    // マウスカーソルが重なっている（最前面のスプライトがこれ、またはこれを親に持つ子）
        bool clicked = false;    // hoveredの状態で、このフレームに左ボタンが押された（ScrollViewComponent の枠の中では、離された）
        bool pressed = false;    // これの上で左ボタンを押し、押したまま重なっている（押し込みの見た目用）
    };
}    // namespace Tsukino::BuiltIn::ECS
