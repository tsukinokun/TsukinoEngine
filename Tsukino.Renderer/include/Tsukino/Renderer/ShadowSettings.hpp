//----------------------------------------------------------------------------
//! @file   ShadowSettings.hpp
//! @brief  カスケードシャドウの調整値
//! @detail ディレクショナルライトの影（カスケードシャドウマップ）の範囲・分割・解像度を、
//!         ゲームごと・シーンごとに変えるための値をまとめます。
//!         通常は DirectionalLightComponent の shadow に書き、LightSystem が Renderer へ渡します。
//----------------------------------------------------------------------------
#pragma once
#include <Tsukino/Core/typedef.hpp>

// 名前空間 : Tsukino::Renderer
namespace Tsukino::Renderer {

    //------------------------------------------------------------------------
    //! カスケードシャドウの調整値です。
    //! @note  既定値は「1ユニット = 1m」で、一般的な一人称・三人称のカメラを想定した値。
    //!        ワールドのスケールやカメラの距離が違うゲームでは distance / splitStart / casterMargin を
    //!        そのスケールに合わせて設定すること（いずれも長さの次元を持つ）。
    //!        カスケードの枚数は b0 のレイアウトとシェーダーに直結するため、ここでは変えられない
    //!        （kShadowCascadeCount）
    //------------------------------------------------------------------------
    struct ShadowSettings {
        //! 影を出す最大の奥行き（カメラのビュー空間 z）。最も外側のカスケードの奥側になる。
        //! カメラの farZ がこれより手前なら farZ で切る
        float distance = 150.0f;

        //! 分割の式を始める奥行き（カメラのビュー空間 z）。0 ならカメラの near から始める。
        //! カメラから注視点まで何も写らない TPS カメラでは、注視点の手前あたりにすると
        //! 写っている物へカスケードの解像度が回る。これより手前はカスケード0がまとめて受け持つ
        float splitStart = 0.0f;

        //! 分割距離の対数寄せ具合（practical split scheme の λ）。1.0で完全な対数、0.0で等間隔。
        //! 大きいほど近景へ解像度が寄る
        float splitLambda = 0.75f;

        //! シャドウマップ1枚の一辺（ピクセル）。kMinMapSize〜kMaxMapSize の2のべき乗に丸めて使う。
        //! 変えるとシャドウマップを作り直すので、毎フレーム揺らす値ではない
        u32 mapSize = 2048;

        //! カスケードを包む球より光の来る側へ、どこまで投影者（高い木や崖）を拾うか（ワールド距離）。
        //! 足りないと、範囲の外にある高い物の影が欠ける
        float casterMargin = 100.0f;

        static constexpr u32 kMinMapSize = 512;     //!< mapSize の下限
        static constexpr u32 kMaxMapSize = 8192;    //!< mapSize の上限（D3D11 のテクスチャの一辺の上限は16384だが、4枚ぶんのメモリを考えて抑える）
    };

}    // namespace Tsukino::Renderer
