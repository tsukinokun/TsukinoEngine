//----------------------------------------------------------------------------
//! @file   CullMode.hpp
//! @brief  面カリングの列挙型の宣言
//----------------------------------------------------------------------------
#pragma once
// 名前空間 : Tsukino::Renderer
namespace Tsukino::Renderer {
    //----------------------------------------------------------------------------
    //! 面カリングの種類を表す列挙型です。
    //----------------------------------------------------------------------------
    enum class CullMode {
        None,    // 両面を描く（草の板ポリ・スプライト・影など）
        Back,    // 裏面を捨てる（閉じたメッシュ。カメラがめり込んでも内面が見えない）
        Front,   // 表面を捨てる（拡縮がマイナスで鏡像になったメッシュは巡回順が逆になるので、これで Back と同じ見え方になる）
    };

}    // namespace Tsukino::Renderer
