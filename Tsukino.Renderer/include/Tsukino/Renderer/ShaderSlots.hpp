#pragma once

// 名前空間 : Tsukino::Renderer
namespace Tsukino::Renderer {

    //--------------------------------------------------------------
    //! @brief 定数バッファスロット (b*)
    //--------------------------------------------------------------
    enum class CBSlot : unsigned int {
        Scene     = 0,    //!< b0 : フレーム共通データ（ビュー・プロジェクション・ライト）
        Transform = 1,    //!< b1 : オブジェクト固有データ（ワールド行列）
        Material  = 2,    //!< b2 : マテリアルデータ（PBRパラメータ）
        Skinning  = 3,    //!< b3 : ボーン行列（スキニングあり限定）
        Sky       = 4,    //!< b4 : 大気散乱パラメータ（CBufferSky, スカイパス用。PS専用）
        Lights    = 5,    //!< b5 : 点光源・スポットライト配列（CBufferLights, ディファードLightingパス用）

        SkinningPrev = 6,    //!< b6 : 前フレームのボーン行列（CBufferSkinningPrev, 速度バッファ生成用。VS専用）
        MotionBlur   = 7,    //!< b7 : モーションブラーパラメータ（CBufferMotionBlur, ブラーパス用。PS専用）

        Fog          = 8,    //!< b8 : フォグパラメータ（CBufferFog, フォグパス用。PS専用）

        AmbientParticle = 9,    //!< b9 : 環境パーティクルのパラメータ（CBufferAmbientParticle, 環境パーティクルパス用。VS専用）

        //--------------------------------------------------------------
        // b10 : IBL（スカイ由来の環境光）パラメータ（CBufferIBL, Lighting.ps.hlsl /
        //       Model.ps.hlsl 共用。PS専用）
        //--------------------------------------------------------------
        IBL = 10,    //!< b10 : IBLパラメータ（CBufferIBL）

        //--------------------------------------------------------------
        // b11 : IBLベイク専用の一時バッファ（CBufferIBLBake）
        //
        // IBLのキャプチャ/irradiance畳み込み/スペキュラプレフィルタは起動時に
        // 数十回描画するだけの一発ベイクで、他の演出とは実行タイミングが
        // 重ならない（b4のCBufferSkyがスカイパス実行中だけバインドされるのと
        // 同じ考え方）。そのため恒久的にIBLへ割り当てるのではなく、ベイク中
        // だけ一時的にここを使う。ベイクが終わった後の定常フレームでは
        // 何もバインドしない＝実質的に空いたまま
        //--------------------------------------------------------------
        IBLBake = 11,    //!< b11 : IBLベイク一時パラメータ（CBufferIBLBake, PS専用）

        //--------------------------------------------------------------
        // b12 / b13 : ゲーム予約枠
        //
        // エンジンはこの範囲へ演出を足さない。ゲームが自前のシェーダーで
        // 何かを描くとき、DrawCommand::userConstantBuffer 経由でここへ
        // バインドする。
        //
        // この枠を切ったのは、以前は「演出を1つ足す＝エンジンにCBSlotと
        // Set関数とメンバとRender()のフックを足す」以外に道が無く、
        // ゲーム固有の演出までエンジンへ流れ込んでいたため。
        // 14本しかないスロットを演出が食い潰す構造そのものを断つ。
        //
        // なお時間・解像度といった共通の素材は CBufferScene(b0) にあるので、
        // それだけで足りる演出はこの枠すら使わずに済む
        //--------------------------------------------------------------
        User0 = 12,    //!< b12 : ゲーム定義の定数バッファ
        User1 = 13,    //!< b13 : 同上（2本目）
    };

    //--------------------------------------------------------------
    //! @brief テクスチャスロット (t*)
    //! @note  t0〜t7  : マテリアルテクスチャ（描画オブジェクトごとに差し替え）
    //!        t8〜t15 : システムテクスチャ（フレーム単位で固定）
    //--------------------------------------------------------------
    enum class SRVSlot : unsigned int {
        // --- マテリアルテクスチャ (t0〜t7) ---
        Albedo            = 0,    //!< t0 : アルベドマップ
        Normal            = 1,    //!< t1 : ノーマルマップ
        MetallicRoughness = 2,    //!< t2 : メタリック・ラフネスマップ (G=roughness, B=metallic)
        Emissive          = 3,    //!< t3 : エミッシブマップ
        AO                = 4,    //!< t4 : アンビエントオクルージョンマップ
        // t5〜t7 : 将来のマテリアルテクスチャ拡張枠

        // --- システムテクスチャ (t8〜t15) ---
        ShadowMap = 8,    //!< t8 : シャドウマップ

        // --- G-Buffer（ディファードLightingパスで読む。GBufferパスの出力と対応） ---
        GBufferAlbedo   = 9,     //!< t9  : G-Buffer0 (rgb: albedo)
        GBufferNormal   = 10,    //!< t10 : G-Buffer1 (rgb: ワールド法線, a: ShadingModel ID)
        GBufferMaterial = 11,    //!< t11 : G-Buffer2 (r: metallic, g: roughness, b: specular, a: AO)
        GBufferEmissive = 12,    //!< t12 : G-Buffer3 (rgb: emissive + リム発光)
        GBufferDepth    = 13,    //!< t13 : 深度（G-Bufferパスと共有するDSVのSRVビュー）
        GBufferWorldPos = 14,    //!< t14 : G-Buffer4 (rgb: ワールド座標。頂点シェーダー補間値そのまま)
        GBufferVelocity = 15,    //!< t15 : G-Buffer5 (rg: 1フレームあたりのUV移動量。モーションブラーパスで読む)

        // --- 頂点シェーダー専用 (t16〜) ---
        //! SRVスロットはシェーダーステージごとに独立しているため、t0でもPSのアルベドとは
        //! 衝突しない。それでも番号を分けているのは、どのスロットに何が入るかを
        //! 1箇所で見渡せる状態を保つため（デバッグ時にスロット番号だけで特定できる）
        InstanceData = 16,    //!< t16 : インスタンスごとのデータ（DrawCommand::instanceData。頂点シェーダー専用）

        // --- IBL（スカイ由来の環境光。Lighting.ps.hlsl / Model.ps.hlsl 共用。PS専用） ---
        IBLIrradiance          = 17,    //!< t17 : 拡散IBL用irradianceキューブマップ
        IBLPrefilteredSpecular = 18,    //!< t18 : 鏡面IBL用プレフィルタ済みキューブマップ（ミップ=ラフネス）
        IBLBRDFLUT             = 19,    //!< t19 : split-sum用BRDF積分LUT（2D, R=スケール, G=バイアス）

        //! t20 : IBLベイク専用の一時入力（キャプチャキューブ）。b11と同じ理由で
        //!       ベイク中だけ使い、定常フレームでは何もバインドしない
        IBLCaptureSource = 20,
    };

    //--------------------------------------------------------------
    //! @brief サンプラースロット (s*)
    //! @note  SRVSlotと同じブロック境界に揃える
    //--------------------------------------------------------------
    enum class SamplerSlot : unsigned int {
        // --- マテリアルサンプラー (s0〜s7) ---
        Material = 0,    //!< s0 : マテリアルテクスチャ共通サンプラー

        // --- システムサンプラー (s8〜s15) ---
        ShadowMap = 8,     //!< s8  : シャドウマップ用比較サンプラー（SampleCmpLevelZero用）
        GBuffer   = 9,     //!< s9  : G-Buffer読み取り用ポイントサンプラー（LightingパスでPointClampを使う）
        IBL       = 10,    //!< s10 : IBLテクスチャ読み取り用サンプラー（LinearClampを流用。トライリニアでミップ間を補間する）
    };
}    // namespace Tsukino::Renderer
