#pragma once

// 名前空間 : Tsukino::Renderer
namespace Tsukino::Renderer {

    //--------------------------------------------------------------
    //! @enum BlendMode
    //! @brief パイプラインのブレンドモード
    //--------------------------------------------------------------
    enum class BlendMode {
        Opaque,      //!< 不透明（デフォルト）
        Alpha,       //!< アルファブレンド（半透明）
        Additive,    //!< 加算合成
        DepthOnly,   //!< 色を書かず深度のみ埋める（半透明モデルの自己重なり対策用の事前パス）
    };
}    // namespace Tsukino::Renderer
