//----------------------------------------------------------------------------
//! @file   GpuProfiler.hpp
//! @brief  bgfx 版のパス単位の GPU タイマーの宣言
//! @detail Tsukino.Renderer の内部専用ヘッダです。bgfx のプロファイラ（BGFX_DEBUG_PROFILER）が
//!         ビューごとに測った GPU 時間を、ビューの番号から GpuPass へ振り分けて足し合わせます。
//!         bgfx は結果が届いたフレームの値を返すので、数フレーム遅れた値になります。
//----------------------------------------------------------------------------
#pragma once
#include <Tsukino/Renderer/GpuTiming.hpp>

// 名前空間 : Tsukino::Renderer
namespace Tsukino::Renderer {
    //------------------------------------------------------------------------
    //! パス単位の GPU 時間を計測するクラスです。
    //! @note  GPU のタイマーが使えない環境では、結果は valid = false のままになる
    //------------------------------------------------------------------------
    class GpuProfiler {
    public:
        //------------------------------------------------------------------------
        //! bgfx にビューごとの統計を集めさせます。
        //------------------------------------------------------------------------
        void Initialize();

        //------------------------------------------------------------------------
        //! bgfx の統計から、届いているフレームの GPU 時間を読み出します。
        //! @return パスごとの GPU 時間（読めなかったフレームは、最後に読めた値を持ち越す）
        //! @note  Render() の先頭で1回だけ呼ぶ
        //------------------------------------------------------------------------
        [[nodiscard]]
        const GpuFrameTimings& Collect();

    private:
        GpuFrameTimings m_latest;    // 最後に読み出せた結果
    };
}    // namespace Tsukino::Renderer
