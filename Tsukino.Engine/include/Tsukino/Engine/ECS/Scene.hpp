#pragma once
#include <Tsukino/Core/ECS/Registry/Registry.hpp>
#include <Tsukino/Engine/ECS/SystemManager.hpp>
#include <Tsukino/Core/ECS/Event/EventBus.hpp>

#include <memory>
#include <utility>

// 名前空間 : Tsukino::ECS
namespace Tsukino::ECS {
    //-------------------------------------------------------------
    //! @class  Scene
    //! @brief  ECSを使用したシーン管理クラス
    //-------------------------------------------------------------
    class Scene {
    public:
        //-------------------------------------------------------------
        //! @brief  デフォルトコンストラクタ
        //-------------------------------------------------------------
        Scene() = default;

        //-------------------------------------------------------------
        //! @brief  デストラクタ
        //-------------------------------------------------------------
        ~Scene() = default;

        //-------------------------------------------------------------
        // シーン初期化
        //-------------------------------------------------------------
        void Initialize();

        //-------------------------------------------------------------
        // 毎フレームの更新
        //! @param  deltaTime [in] 前フレームからの経過時間
        //-------------------------------------------------------------
        void Update(float deltaTime);

        //-------------------------------------------------------------
        //! @brief  シーンの終了処理
        //! @details
        //! System が生きている状態で全エンティティを破棄してから System を手放す。
        //! シーンを破棄する側（GameSceneManager）が必ず呼ぶこと。
        //-------------------------------------------------------------
        void Shutdown();

        //-------------------------------------------------------------
        // エンティティの生成
        //! @return 生成されたエンティティ
        //-------------------------------------------------------------
        [[nodiscard]]
        Entity CreateEntity();

        //-------------------------------------------------------------
        // エンティティの破棄
        //! @param  entity [in] 破棄するエンティティ
        //-------------------------------------------------------------
        void DestroyEntity(Entity entity);

        //-------------------------------------------------------------
        // レジストリへのアクセス
        //! @return Registryの参照
        //-------------------------------------------------------------
        [[nodiscard]]
        Registry& GetRegistry() { return m_registry; }

        //-------------------------------------------------------------
        // システムの追加（ヘルパー関数）
        //! @param  system   [in] 追加するシステム
        //! @param  priority [in] システムの優先度（小さいほど先に更新される）
        //-------------------------------------------------------------
        void AddSystem(std::shared_ptr<ISystem> system, int priority = 0);

        //-------------------------------------------------------------
        //! @brief  EventBus へのアクセス
        //! @return EventBus の参照
        //! @note   System のコンストラクタに渡して Subscribe させる
        //-------------------------------------------------------------
        [[nodiscard]]
        EventBus& GetEventBus() { return m_eventBus; }

    private:
        //-------------------------------------------------------------
        //! @note 【この宣言順は破棄順序の設計であり、並べ替えてはならない】
        //!
        //! メンバは宣言の逆順に破棄されるため、上に書いたものほど長生きする。
        //!
        //!   破棄順: m_systemManager → m_registry → m_eventBus
        //!
        //! - System は ScopedConnection をメンバに持ち、破棄時に EventBus へ
        //!   Unsubscribe を投げる。よって EventBus は System より長生きが必須。
        //! - System のデストラクタは Registry 上のリソース（物理ボディ等）を
        //!   参照しうるため、Registry も System より長生きが必須。
        //!
        //! 以前は m_eventBus が最後に宣言されており、System より先に破棄されて
        //! いたため、シーン切替とアプリ終了のたびに破棄済み EventBus への
        //! アクセス（use-after-free）が発生していた。
        //-------------------------------------------------------------
        EventBus      m_eventBus;         //!< イベントの管理（最も長生きさせる）
        Registry      m_registry;         //!< エンティティとコンポーネントの管理
        SystemManager m_systemManager;    //!< システムの管理（最初に破棄する）
    };
}    // namespace Tsukino::ECS
