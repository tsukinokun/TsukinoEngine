#pragma once
#include <Tsukino/Core/ECS/Registry/Registry.hpp>
#include <Tsukino/Engine/ECS/SystemManager.hpp>
#include <Tsukino/Core/ECS/Event/EventBus.hpp>

#include <memory>
#include <utility>

// 名前空間 : Tsukino::ECS
namespace Tsukino::ECS {
    //-------------------------------------------------------------
    //! @class  Scene
    //! @brief  ECSを使用したシーン管理クラス
    //-------------------------------------------------------------
    class Scene {
    public:
        //-------------------------------------------------------------
        //! @brief  デフォルトコンストラクタ
        //-------------------------------------------------------------
        Scene() = default;

        //-------------------------------------------------------------
        //! @brief  デストラクタ
        //-------------------------------------------------------------
        ~Scene() = default;

        //-------------------------------------------------------------
        // シーン初期化
        //-------------------------------------------------------------
        void Initialize();

        //-------------------------------------------------------------
        // 毎フレームの更新
        //! @param  deltaTime [in] 前フレームからの経過時間
        //-------------------------------------------------------------
        void Update(float deltaTime);

        //-------------------------------------------------------------
        // エンティティの生成
        //! @return 生成されたエンティティ
        //-------------------------------------------------------------
        [[nodiscard]]
        Entity CreateEntity();

        //-------------------------------------------------------------
        // エンティティの破棄
        //! @param  entity [in] 破棄するエンティティ
        //-------------------------------------------------------------
        void DestroyEntity(Entity entity);

        //-------------------------------------------------------------
        // レジストリへのアクセス
        //! @return Registryの参照
        //-------------------------------------------------------------
        [[nodiscard]]
        Registry& GetRegistry() { return m_registry; }

        //-------------------------------------------------------------
        // システムの追加（ヘルパー関数）
        //! @param  system   [in] 追加するシステム
        //! @param  priority [in] システムの優先度（小さいほど先に更新される）
        //-------------------------------------------------------------
        void AddSystem(std::shared_ptr<ISystem> system, int priority = 0);

        //-------------------------------------------------------------
        //! @brief  EventBus へのアクセス
        //! @return EventBus の参照
        //! @note   System のコンストラクタに渡して Subscribe させる
        //-------------------------------------------------------------
        [[nodiscard]]
        EventBus& GetEventBus() { return m_eventBus; }

    private:
        Registry      m_registry;         //!< エンティティとコンポーネントの管理
        SystemManager m_systemManager;    //!< システムの管理
        EventBus      m_eventBus;         //!< イベントの管理
    };
}    // namespace Tsukino::ECS
