//--------------------------------------------------------------
//! @file   AudioManager.hpp
//! @brief  オーディオ管理システムのクラス定義
//! @author 山﨑愛
//--------------------------------------------------------------
#pragma once

#include <memory>
#include <string>

// 前方宣言
namespace Tsukino::Asset {
    class AudioAsset;
}

// 名前空間 : Tsukino::Audio
namespace Tsukino::Audio {

    // 前方宣言
    class AudioContext;    // バックエンド(XAudio2等)の隠蔽

    //--------------------------------------------------------------
    //! @class  AudioManager
    //! @brief  音声の再生、停止、音量等の状態管理を行うクラス
    //--------------------------------------------------------------
    class AudioManager {
    public:
        //--------------------------------------------------------------
        //! @brief コンストラクタ
        //--------------------------------------------------------------
        AudioManager();

        //--------------------------------------------------------------
        //! @brief デストラクタ
        //--------------------------------------------------------------
        ~AudioManager();

        //--------------------------------------------------------------
        // コピー・ムーブ禁止（エンジン側で一元管理するため）
        //--------------------------------------------------------------
        AudioManager(const AudioManager&)            = delete;
        AudioManager& operator=(const AudioManager&) = delete;
        AudioManager(AudioManager&&)                 = delete;
        AudioManager& operator=(AudioManager&&)      = delete;

        //--------------------------------------------------------------
        // オーディオマネージャーを初期化する関数
        //! @return true: 初期化成功, false: 初期化失敗
        //--------------------------------------------------------------
        [[nodiscard]]
        bool Initialize();

        //--------------------------------------------------------------
        // 更新関数（毎フレーム呼び出す）
        //! @param deltaTime [in] 前フレームからの経過時間
        //--------------------------------------------------------------
        void Update(float deltaTime);

        //--------------------------------------------------------------
        // 音声を再生する
        //! @param audioAsset       [in] 再生対象のオーディオアセット（AssetManagerでロード済みのもの）
        //! @param isLoop           [in] ループ再生するかどうか
        //! @param volume           [in] 再生音量（0.0f ~ 1.0f）
        //--------------------------------------------------------------
        void Play(const Tsukino::Asset::AudioAsset& audioAsset, bool isLoop = false, float volume = 1.0f);

        //--------------------------------------------------------------
        // 特定の音声を停止する
        //! @param audioAsset [in] 停止対象のオーディオアセット
        //--------------------------------------------------------------
        void Stop(const Tsukino::Asset::AudioAsset& audioAsset);

        //--------------------------------------------------------------
        // 全ての音声を停止する
        //--------------------------------------------------------------
        void StopAll();

        //--------------------------------------------------------------
        // 特定の音声が再生中か確認する
        //! @param audioAsset [in] 確認対象のオーディオアセット
        //! @return true: 再生中, false: 停止中または存在しない
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsPlaying(const Tsukino::Asset::AudioAsset& audioAsset) const;

        //--------------------------------------------------------------
        // マスター音量を設定する
        //! @param volume [in] 全体の音量（0.0f ~ 1.0f）
        //--------------------------------------------------------------
        void SetMasterVolume(float volume);

        //--------------------------------------------------------------
        // マスター音量を取得する
        //! @return 現在の全体音量
        //--------------------------------------------------------------
        [[nodiscard]]
        float GetMasterVolume() const;

    private:
        std::unique_ptr<AudioContext> m_audioContext;    //!< バックエンド（XAudio2等）を隠蔽するコンテキスト
        float                         m_masterVolume;    //!< 全体の音量
    };

}    // namespace Tsukino::Audio
