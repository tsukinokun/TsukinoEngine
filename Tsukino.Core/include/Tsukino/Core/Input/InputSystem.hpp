//--------------------------------------------------------------
//! @file   InputSystem.hpp
//! @brief  入力管理システムのクラス定義
//! @author 山﨑愛
//--------------------------------------------------------------
#pragma once

#include <Tsukino/Core/Input/Gamepad.hpp>
#include <Tsukino/Core/Input/GamepadCodes.hpp>
#include <Tsukino/Core/Input/KeyCodes.hpp>

#include <hlsl++.h>

#include <array>
#include <vector>
// 名前空間 : Tsukino::Input
namespace Tsukino::Input {
    //--------------------------------------------------------------
    //! @class  InputSystem
    //! @brief  キーボード・マウスの状態監視と判定を行うクラス
    //--------------------------------------------------------------
    class InputSystem {
    public:
        //--------------------------------------------------------------
        //! @brief コンストラクタ
        //--------------------------------------------------------------
        InputSystem();

        //--------------------------------------------------------------
        //! @brief デストラクタ
        //--------------------------------------------------------------
        ~InputSystem() = default;

        //--------------------------------------------------------------
        // コピー・ムーブ禁止（EngineIntegrationで一元管理するため）
        //--------------------------------------------------------------
        InputSystem(const InputSystem&)            = delete;
        InputSystem& operator=(const InputSystem&) = delete;

        //--------------------------------------------------------------
        // 更新関数
        //--------------------------------------------------------------
        void Update();

        // --- キー・マウスボタン判定 ---

        //--------------------------------------------------------------
        // ボタンが押されているか（押しっぱなし）
        //! @param code [in] 判定したいキーコード
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsKeyDown(KeyCode code) const;

        //--------------------------------------------------------------
        // ボタンが押された瞬間か
        //! @param code [in] 判定したいキーコード
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsKeyPressed(KeyCode code) const;

        //--------------------------------------------------------------
        // どれかが押された瞬間か
        //! @return
        //--------------------------------------------------------------
        [[nodiscard]]
        bool AnyKeyPressed() const;

        //--------------------------------------------------------------
        // ボタンが離された瞬間か
        //! @param code [in] 判定したいキーコード
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsKeyReleased(KeyCode code) const;

        // --- マウス情報取得 ---

        //--------------------------------------------------------------
        // マウスのスクリーン座標を取得
        //! @param x [out] マウスのX座標を格納する変数へのポインタ
        //! @param y [out] マウスのY座標を格納する
        //--------------------------------------------------------------
        void GetMousePosition(i32* x, i32* y) const;

        //--------------------------------------------------------------
        // 前フレームからのマウス移動量を取得
        //! @param dx [out] X軸の移動量を格納する変数へのポインタ
        //! @param dy [out] Y軸の移動量を格納する
        //--------------------------------------------------------------
        void GetMouseDelta(i32* dx, i32* dy) const;

        //--------------------------------------------------------------
        // マウスホイールの回転量を取得（奥に回すとプラス、手前はマイナス）
        //! @return 累積ホイール回転量
        //--------------------------------------------------------------
        [[nodiscard]]
        float GetWheelDelta() const {
            return m_wheelDelta;
        }

        // --- ゲームパッド ---

        //--------------------------------------------------------------
        //! 全スロットのゲームパッドの状態を読み直します。
        //! @param  [in] deltaTime     前フレームからの経過秒数
        //! @param  [in] windowFocused ウィンドウにフォーカスがあるか。無いあいだは中立として扱い、振動も止める
        //! @note   シーンの更新より前に毎フレーム1回呼ぶ（EngineAPI::Update が呼ぶ）
        //--------------------------------------------------------------
        void PollGamepads(float deltaTime, bool windowFocused);

        //--------------------------------------------------------------
        //! スロットを指定してゲームパッドを得ます。
        //! @param  [in] index スロット番号（0〜kMaxGamepads-1）
        //! @return そのスロットのゲームパッド
        //--------------------------------------------------------------
        [[nodiscard]]
        const Gamepad& GetGamepad(u32 index) const;

        //--------------------------------------------------------------
        //! いずれかのゲームパッドでボタンが押されているかを返します（押しっぱなし）。
        //! @param  [in] button 判定するボタン
        //! @return 押されていれば true
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsButtonDown(GamepadButton button) const;

        //--------------------------------------------------------------
        //! いずれかのゲームパッドでボタンが押された瞬間かを返します。
        //! @param  [in] button 判定するボタン
        //! @return このフレームに押されたなら true
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsButtonPressed(GamepadButton button) const;

        //--------------------------------------------------------------
        //! いずれかのゲームパッドでボタンが離された瞬間かを返します。
        //! @param  [in] button 判定するボタン
        //! @return このフレームに離されたなら true
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsButtonReleased(GamepadButton button) const;

        //--------------------------------------------------------------
        //! 左スティックの傾きを返します。複数台あるときは最も大きく倒している1台の値です。
        //! @return −1〜1 に正規化した値（上が +y）
        //--------------------------------------------------------------
        [[nodiscard]]
        hlslpp::float2 GetLeftStick() const;

        //--------------------------------------------------------------
        //! 右スティックの傾きを返します。複数台あるときは最も大きく倒している1台の値です。
        //! @return −1〜1 に正規化した値（上が +y）
        //--------------------------------------------------------------
        [[nodiscard]]
        hlslpp::float2 GetRightStick() const;

        //--------------------------------------------------------------
        //! 指定したスティックの傾きを返します。
        //! @param  [in] stick 読むスティック
        //! @return −1〜1 に正規化した値。None なら 0
        //--------------------------------------------------------------
        [[nodiscard]]
        hlslpp::float2 GetStick(GamepadStick stick) const;

        //--------------------------------------------------------------
        //! 接続されている全てのゲームパッドを振動させます。
        //! @param  [in] lowFrequency    左側（低周波・重い）モーターの強さ（0〜1）
        //! @param  [in] highFrequency   右側（高周波・軽い）モーターの強さ（0〜1）
        //! @param  [in] durationSeconds 振動させる秒数
        //--------------------------------------------------------------
        void SetGamepadVibration(float lowFrequency, float highFrequency, float durationSeconds);

        //--------------------------------------------------------------
        //! 全てのゲームパッドの振動を止めます。
        //--------------------------------------------------------------
        void StopGamepadVibration();

        //--------------------------------------------------------------
        //! 全てのゲームパッドのスティックのデッドゾーンを設定します。
        //! @param  [in] deadZone 0〜1 の値
        //--------------------------------------------------------------
        void SetGamepadStickDeadZone(float deadZone);

        //--------------------------------------------------------------
        //! 全てのゲームパッドのトリガーのしきい値を設定します。
        //! @param  [in] threshold 0〜1 の値
        //--------------------------------------------------------------
        void SetGamepadTriggerThreshold(float threshold);

        //--------------------------------------------------------------
        //! いずれかのゲームパッドが接続されているかを返します。
        //! @return 1台でも接続されていれば true
        //--------------------------------------------------------------
        [[nodiscard]]
        bool IsAnyGamepadConnected() const;

        //--------------------------------------------------------------
        //! 最後に操作された入力機器を返します。操作表示の切り替えに使います。
        //! @return キーボード・マウスか、ゲームパッドか
        //--------------------------------------------------------------
        [[nodiscard]]
        InputDevice GetLastInputDevice() const {
            return m_lastInputDevice;
        }

        // --- エンジン内部用（Windowクラス等から呼ばれる） ---

        //--------------------------------------------------------------
        // キー状態を直接書き換える
        //! @param code   [in] 書き換えたいキーコード
        //! @param isDown [in] キーが押されている状態にする
        //--------------------------------------------------------------
        void SetKeyState(KeyCode code, bool isDown);

        //--------------------------------------------------------------
        // マウス座標を更新する
        //! @param x [in] 新しいX座標
        //! @param y [in] 新しいY座標
        //--------------------------------------------------------------
        void SetMousePosition(i32 x, i32 y);

        //--------------------------------------------------------------
        // マウスホイール量を加算する
        //! @param delta [in] 加算したいホイール回転量（奥に回すとプラス、手前はマイナス）
        //--------------------------------------------------------------
        void AddWheelDelta(float delta);

        //--------------------------------------------------------------
        //! キーボードかマウスが操作されたことを知らせます。
        //! @note   最後に操作された入力機器をキーボード・マウスへ切り替える。
        //!         Win32 のメッセージを受けた側（EngineIntegration）が、キーの押下・クリック・ホイール・
        //!         実際のマウス移動のときだけ呼ぶ。ゲームがカーソルを中央へ戻したときの移動では呼ばない
        //--------------------------------------------------------------
        void NotifyKeyboardMouseActivity();

        //--------------------------------------------------------------
        // 全てのキー・ボタンの押下状態をクリアする
        //! @details
        //! ウィンドウがフォーカスを失ったときに呼ぶ。
        //! キーを押したまま Alt+Tab すると WM_KEYUP が移動先のウィンドウへ
        //! 届くため、こちらには離した通知が来ず、押しっぱなしの状態が残る。
        //!
        //! 前フレームの状態も同時にクリアするため、フォーカスが戻った直後に
        //! IsKeyReleased() が誤って true を返すこともない。
        //--------------------------------------------------------------
        void ClearAllKeys();

    private:
        // キー状態の配列（KeyCodeの最大値に合わせて確保）
        // Win32の仮想キーコードは256個以内に収まる
        std::array<bool, 256> m_currentKeys;     //!< 現フレームの状態
        std::array<bool, 256> m_previousKeys;    //!< 前フレームの状態

        i32 m_mouseX = 0, m_mouseY = 0;            //!< 現在のマウス座標
        i32 m_prevMouseX = 0, m_prevMouseY = 0;    //!< 前フレームのマウス座標

        float m_wheelDelta = 0.0f;    //!< 累積ホイール回転量

        std::array<Gamepad, kMaxGamepads> m_gamepads;    //!< スロットごとのゲームパッド

        InputDevice m_lastInputDevice = InputDevice::KeyboardMouse;    //!< 最後に操作された入力機器
    };

}    // namespace Tsukino::Input
