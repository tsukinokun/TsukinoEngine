#pragma once

//--------------------------------------------------------------
//! <windows.h> は既定で min / max マクロを定義する。
//! これが hlsl++ の std::min / std::max 呼び出しと衝突し、
//! 「hlsl++ を windows.h より後に include したときだけ壊れる」
//! という include 順依存のビルドエラーになる。
//!
//! 公開ヘッダから windows.h を取り込む箇所は、直接 include せず
//! 必ずこのヘッダを通すこと。定義を1箇所に集約することで、
//! ヘッダごとに NOMINMAX を書き散らすのを防ぐ。
//!
//! 既に定義済みなら上書きしない（取り込み側の設定を尊重する）。
//--------------------------------------------------------------
#ifndef NOMINMAX
#    define NOMINMAX
#endif

#ifndef WIN32_LEAN_AND_MEAN
#    define WIN32_LEAN_AND_MEAN
#endif

#include <windows.h>
