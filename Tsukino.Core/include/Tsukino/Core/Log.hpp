//--------------------------------------------------------------
//! @file   Log.hpp
//! @brief  ログ出力クラスの宣言
//! @author 山﨑愛
//--------------------------------------------------------------
#pragma once
#include <string>
// 名前空間 : Tsukino::Core
namespace Tsukino::Core {
    //--------------------------------------------------------------
    //! @class   Log
    //! @brief   ログ出力クラス
    //! @details ログレベルに応じてメッセージを出力するクラス
    //!          既定ではOutputDebugStringAにのみ出力するため、デバッガの外からは何も見えない。
    //!          SetLogFile()を呼ぶとファイルへも追記されるようになる
    //--------------------------------------------------------------
    class Log {
    public:
        //--------------------------------------------------------------
        // ログ出力関数
        //! @param msg 出力するメッセージ
        //--------------------------------------------------------------
        static void Info(const std::string& msg);

        //--------------------------------------------------------------
        // 警告ログ出力関数
        //! @param msg 出力するメッセージ
        //--------------------------------------------------------------
        static void Warn(const std::string& msg);

        //--------------------------------------------------------------
        // エラーログ出力関数
        //! @param msg 出力するメッセージ
        //--------------------------------------------------------------
        static void Error(const std::string& msg);

        //--------------------------------------------------------------
        //! ログの出力先ファイルを設定します。
        //! 以降、OutputDebugStringAへの出力に加えて、指定したファイルへも追記されます。
        //! 親ディレクトリが存在しない場合は作成します。
        //! @param [in] filePath 出力先のファイルパス
        //--------------------------------------------------------------
        static void SetLogFile(const std::string& filePath);

        //--------------------------------------------------------------
        //! ファイルへのログ出力を停止します。
        //--------------------------------------------------------------
        static void CloseLogFile();

    private:
        //--------------------------------------------------------------
        //! レベル表記を付けた1行を、デバッグ出力とログファイルへ書き出します。
        //! @param [in] level レベルの表記（"Info"など）
        //! @param [in] msg   出力するメッセージ
        //--------------------------------------------------------------
        static void Write(const char* level, const std::string& msg);

        static std::string s_LogFilePath;    // 空の間はファイルへ出力しない
    };
}    // namespace Tsukino::Core
