//-------------------------------------------------------------
//! @file   HotReload.hpp
//! @brief  調整用ファイルのホットリロード
//! @detail 保存し直されたファイルを実行中に読み直します。読み直せたら「Hot reloaded:」と、
//!         前に読めた中身との差分（JSONなら「Hot reload changed:」の行）をログへ出します。
//!         TSUKINO_ENABLE_HOT_RELOAD（DebugFeatures.hpp。Debugビルドの既定）が無いときは、どの関数も何もしません。
//-------------------------------------------------------------
#pragma once
#include <Tsukino/Core/Path.hpp>

#include <functional>

// 名前空間 : Tsukino::IO::HotReload
namespace Tsukino::IO::HotReload {
    //-------------------------------------------------------------
    //! 監視するファイルを登録します。
    //! @param  path   [in] 監視するファイルのパス
    //! @param  reload [in] 読み直す関数。読み直せたら true、前の値のままにしたら false を返す
    //! @note   どのスレッドから呼んでもよい。reload は Poll を呼んだスレッドで呼ばれる
    //-------------------------------------------------------------
    void Watch(const Tsukino::Core::Path& path, std::function<bool()> reload);

    //-------------------------------------------------------------
    //! 更新されたファイルを読み直します。
    //! @note   EngineAPI::Update がシーンの更新の前に毎フレーム呼ぶ（システムの途中で値が変わらないように）
    //-------------------------------------------------------------
    void Poll();

    //-------------------------------------------------------------
    //! 読み直しを止める・再開します。
    //! @param  paused [in] 止めるか
    //! @note   裏スレッドが同じデータを読んでいる間（ロード画面など）は止めておく
    //-------------------------------------------------------------
    void SetPaused(bool paused);
}    // namespace Tsukino::IO::HotReload
